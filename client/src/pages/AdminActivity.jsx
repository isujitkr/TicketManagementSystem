import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { useDispatch, useSelector } from 'react-redux';
import { fetchActivityFeed } from '../store/adminSlice';
import Pagination from '../components/Pagination';
import { EmptyState, Loader } from '../components/Feedback';
import { formatDate, label } from '../utils/format';

const LIMIT = 20;

export default function AdminActivity() {
  const dispatch = useDispatch();
  const { items, pagination, loading } = useSelector((s) => s.admin.feed);
  const [page, setPage] = useState(1);

  useEffect(() => {
    dispatch(fetchActivityFeed({ page, limit: LIMIT }));
  }, [dispatch, page]);

  return (
    <>
      <div className="page-head">
        <div>
          <h1>Activity log</h1>
          <p className="muted">Every ticket event, generated by the event handlers.</p>
        </div>
      </div>

      <div className="card">
        {loading && items.length === 0 ? (
          <Loader />
        ) : items.length === 0 ? (
          <EmptyState title="No activity yet" />
        ) : (
          <ul className="feed">
            {items.map((a) => (
              <li key={a._id}>
                <span className={`dot ${a.type.replace('.', '-')}`} />
                <div className="feed-body">
                  <div>
                    {a.message}
                    {a.type !== 'ticket.deleted' && a.ticket && (
                      <>
                        {' '}
                        <Link to={`/tickets/${a.ticket}`}>View ticket</Link>
                      </>
                    )}
                  </div>
                  <small className="muted">
                    {label(a.type.split('.')[1])} · {formatDate(a.createdAt)}
                  </small>
                </div>
              </li>
            ))}
          </ul>
        )}

        <Pagination pagination={pagination} onPage={setPage} />
      </div>
    </>
  );
}
